def frames(log2_rows, log3_rows, first_sequence=1, uptime=10000):
    """The rows as frames with zero payloads: the log2 rows first, then the log3 rows."""
    out = []
    for i, (field3, group, function, len6, field7, field8, len9, field11, field12) in enumerate(log2_rows):
        extra = tuple((f, v) for f, v in ((11, field11), (12, field12)) if v is not None)
        out.append(rtnl.frame(rtnl.log2(uptime + i, first_sequence + i, group, function, bytes(len6), field3, field7,
                                        0 if field8 else None, None if len9 is None else bytes(len9), extra)))
    for field2, len3 in log3_rows:
        out.append(rtnl.frame(rtnl.log3(0, field2, None if len3 is None else bytes(len3))))
    return out
